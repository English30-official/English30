// In-Memory Pack Repository Engine
class ContentEngineRepository {
  private packs: Map<string, LearningPack> = new Map();

  constructor() {
    this.registerPack(TRAVEL_A2_PACK);
  }

  public registerPack(pack: LearningPack): void {
    this.packs.set(pack.id, pack);
  }

  public getAllPacks(): LearningPack[] {
    return Array.from(this.packs.values());
  }

  public getPackById(id: string): LearningPack | undefined {
    return this.packs.get(id);
  }

  public getPacksByLevel(level: LevelCode): LearningPack[] {
    return this.getAllPacks().filter((p) => p.level === level);
  }
}

export const contentEngine = new ContentEngineRepository();
